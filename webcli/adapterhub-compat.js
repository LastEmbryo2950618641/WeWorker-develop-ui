/**
 * AdapterHub v2 包兼容层 —— 把 v2 包（extension/commands/*.js ESM 模块）
 * 转译为当前 Chrome 扩展可执行的经典脚本 index.js + wecli.generated.json 路由表。
 *
 * 扩展加载契约（见 extension/background/service-worker.js）：
 * - 发现：adapters/index.json 列表 + adapters/<id>/manifest.json + adapters/<id>/index.js 存在
 * - 注入/加载：adapters/<id>/index.js 作为经典脚本执行，内部 window.__webmcpRegister({...})
 * - 无 tab 直连：tool.handlerName 注册到 direct-frame 的 handlers 表
 *
 * v2 命令模块格式：export async function handler(args, ctx) / export const handler
 * 转译策略：读取模块源码，剥离 ESM 语法后包成 IIFE，把 handler 注册为
 *   `<name>.<id>` 工具（handlerName 同名），args 按命令 schema 校验交由扩展运行时。
 */

import { strFromU8 } from "fflate";

const DEFAULT_ROUTE_DOMAIN = (name) => name; // v2 name 即站点域名

/**
 * 把单个 ESM 命令模块源码转为经典脚本可执行的 handler 表达式。
 * - 去掉 `export default` / `export const|let|var|function|async function` 前缀中的 export
 * - 其余 ESM 语法（import）本就不被经典脚本支持，转为抛错提示
 * 返回 IIFE 求值后的对象源码（挂到临时全局，再取走）
 */
function transpileCommandModule(source, adapterName, commandId) {
  let code = String(source || "");
  // 记录原始长度供报错
  if (/^\s*import\s/m.test(code)) {
    throw new Error(
      `命令 ${commandId} 使用了 import 语句，v2 命令模块须自包含（不允许 ESM import）`
    );
  }
  // 剥离各种 export 形态
  code = code
    .replace(/export\s+default\s+/g, "")
    .replace(/export\s+\{[^}]*\}\s*;?/g, "")
    .replace(/export\s+(async\s+function|function|const|let|var|class)\s/g, "$1 ");
  // 找到 handler：优先命名 handler，退化为第一个函数声明/const fn
  const hasNamed =
    /(?:async\s+function|function|const|let|var)\s+handler\b/.test(code) ||
    /(?:const|let|var)\s+handler\s*=/.test(code);
  if (!hasNamed) {
    // 包装：取模块内第一个 function 声明名为 handler
    const fnName = code.match(
      /(?:async\s+function|function)\s+([A-Za-z_$][\w$]*)\s*\(/
    );
    if (fnName) {
      code += `\n;const handler = ${fnName[1]};`;
    } else {
      throw new Error(`命令 ${commandId} 模块未找到 handler 函数`);
    }
  }
  return code;
}

/**
 * 由 v2 manifest + files 构建兼容层文件。
 * @param {object} manifest v2 manifest（schema_version=2）
 * @param {Map<string,Uint8Array>} files 包内全部文件
 * @returns {{ "index.js": string, "wecli.generated.json": string, "manifest.json": string }}
 *   返回需要额外写入兼容产物的映射（manifest.json 为扩展版 manifest，独立于包内原文件）
 */
export function buildCompatLayer(manifest, files) {
  const adapterName = manifest.name;
  const match = Array.isArray(manifest.match) ? manifest.match : [adapterName];
  const routeDomain = match[0] || DEFAULT_ROUTE_DOMAIN(adapterName);
  const tools = [];
  const parts = [
    `// Generated by webcli adapterhub (v2 compat layer) — do not edit.`,
    `// Adapter: ${adapterName} v${manifest.version}`,
  ];
  for (const command of manifest.commands || []) {
    if (command.runtime !== "extension") continue; // wewright 命令由服务端运行时处理，不进浏览器兼容层
    const moduleEntry = files.get(command.module);
    if (!moduleEntry) continue;
    const source = strFromU8(moduleEntry);
    let body;
    try {
      body = transpileCommandModule(source, adapterName, command.id);
    } catch (err) {
      // 单个命令失败跳过并在 index.js 留注释，不阻断整个 adapter 安装
      parts.push(`// Skipped command ${command.id}: ${err.message}`);
      continue;
    }
    const toolName = `${adapterName}.${command.id}`;
    const parameters =
      command.schema && typeof command.schema === "object"
        ? command.schema
        : { type: "object", properties: {} };
    parts.push(`// ── command: ${command.id} ──`);
    parts.push(`(function () {\n${body}\n;` +
      `window.__webmcpRegister({\n` +
      `  name: ${JSON.stringify(`wecli-${adapterName}-${command.id}`)},\n` +
      `  match: ${JSON.stringify(match)},\n` +
      `  tools: [{\n` +
      `    name: ${JSON.stringify(toolName)},\n` +
      `    publicName: ${JSON.stringify(toolName)},\n` +
      `    handlerName: ${JSON.stringify(toolName)},\n` +
      `    adapterId: ${JSON.stringify(adapterName)},\n` +
      `    routeDomain: ${JSON.stringify(routeDomain)},\n` +
      `    tabDomain: ${JSON.stringify(routeDomain)},\n` +
      `    description: ${JSON.stringify(command.description || command.id)},\n` +
      `    parameters: ${JSON.stringify(parameters)},\n` +
      `    handler: (typeof handler === 'function') ? handler : null,\n` +
      `  }],\n` +
      `});\n})();`);
    tools.push({
      id: command.id,
      publicName: toolName,
      handlerName: toolName,
      adapterId: adapterName,
      routeDomain,
      tabDomain: routeDomain,
      description: command.description || command.id,
      parameters,
      status: "registered",
    });
  }
  const indexJs = parts.join("\n") + "\n";
  const generatedJson = JSON.stringify(
    {
      version: 1,
      adapterId: adapterName,
      match,
      sites: match,
      commandCount: tools.length,
      registeredCommands: tools,
      blockedCommands: [],
      generated_by: "webcli adapterhub v2 compat layer",
    },
    null,
    2
  ) + "\n";

  // 扩展侧 manifest（与包内 v2 manifest 不同：补 id/name/version/match 供扩展发现）
  const extManifest = {
    id: adapterName,
    name: manifest.display || adapterName,
    description: manifest.description || "",
    match,
    requires_auth: false,
    version: manifest.version,
    author: "adapterhub",
    support_files: [],
  };

  return {
    "index.js": indexJs,
    "wecli.generated.json": generatedJson,
    "manifest.json": JSON.stringify(extManifest, null, 2) + "\n",
    __toolCount: tools.length,
  };
}

/** 校验 adapter name 可安全作为目录名（防路径逃逸） */
export function isSafeAdapterName(name) {
  return (
    typeof name === "string" &&
    name.length > 0 &&
    name.length <= 120 &&
    /^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(name) &&
    !name.includes("..")
  );
}

/** 校验 version 可安全拼进文件名/路径 */
export function isSafeVersion(version) {
  return (
    typeof version === "string" &&
    /^v?\d+(\.\d+){0,3}([-+][0-9A-Za-z.-]+)?$/.test(String(version || "").trim())
  );
}

/** zip 条目名安全性（不允许绝对路径/.. 逃逸） */
export function isSafeArchiveEntry(entryName) {
  if (typeof entryName !== "string" || !entryName) return false;
  if (entryName.includes("\\") || entryName.startsWith("/")) return false;
  const normalized = entryName.replace(/\/+/g, "/");
  if (normalized.split("/").some((part) => part === ".." || part === "")) return false;
  return true;
}
