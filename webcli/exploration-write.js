const hash = value => createHash('sha256').update(JSON.stringify(value)).digest('hex');
const clone = value => JSON.parse(JSON.stringify(value));
const object = value => value && typeof value === 'object' && !Array.isArray(value);
const invalid = message => { throw fail('INVALID_WRITE_CASE', message); };
const keys = (value, allowed) => { if (!object(value) || Object.keys(value).some(key => !allowed.includes(key))) invalid('Unsupported write case fields.'); };
export const writeFixtures = run => readGenerationEvidence(run.draft.adapterDir, 'write-verification.json', { optional: true }) || { format: 2, commands: {} };
export const writeProofDigest = run => hash({ package: readPackageDirectory(run.draft.adapterDir).digest, verification: run.verification || {}, fixtures: writeFixtures(run) });
export const plannedWrites = run => (run.plan?.tools || []).filter(tool => tool.risk === 'write').map(tool => `${run.siteKey}.${tool.name.replace(/_/g, '-')}`);

/** No request is sent. This is an author's declaration, not observed evidence. */
export function declareWriteSource(service, run, args) {
  const reason = textArg(args.reason, 'reason');
  const method = textArg(args.method, 'method', 10);
  if (!['POST', 'PUT', 'PATCH', 'DELETE'].includes(method)) throw fail('INVALID_ARGUMENT', 'Write declarations require POST, PUT, PATCH or DELETE.');
  const url = new URL(textArg(args.url, 'url', 4000));
  if (![run.origin, ...(run.allowedOrigins || [])].includes(url.origin) || url.username || url.password || url.hash) throw fail('HTTP_ORIGIN_DENIED', 'Write source must use a task origin without credentials or fragments.');
  const bodyKeys = args.bodyKeys || [];
  if (!Array.isArray(bodyKeys) || bodyKeys.length > 50 || bodyKeys.some(key => typeof key !== 'string' || !/^[A-Za-z][A-Za-z0-9_]{0,63}$/.test(key))) throw fail('INVALID_ARGUMENT', 'bodyKeys must be at most 50 public field names.');
  dataOnly(Object.fromEntries(bodyKeys.map(key => [key, null])));
  const candidate = extractExplorationEvidence({ entries: [{ url: url.href, method,
    requestContentType: bodyKeys.length ? 'application/json' : '', requestBody: bodyKeys.length ? JSON.stringify(Object.fromEntries(bodyKeys.map(key => [key, null]))) : undefined }] }, run.origin, run.allowedOrigins)[0];
  if (!candidate) throw fail('INVALID_ARGUMENT', 'Invalid write source.');
  candidate.declared = true;
  candidate.risk = { level: 'write', confidence: 1, evidence: ['author_declared_write_not_executed'] };
  candidate.observation = { mode: 'declaration', reason, at: new Date().toISOString(), executed: false };
  run.candidates = [...new Map([...run.candidates, candidate].map(item => [item.id, item])).values()].slice(-100);
  service.update(run, 'evidence_ready', 'Write source declared without execution. Author a write plan, implementation and verification fixture.');
  return service.summary(run);
}

function writeCommand(run, tool) {
  if (!plannedWrites(run).includes(tool)) throw fail('INVALID_ARGUMENT', 'Select a write tool generated by this task.');
  const command = readPackageDirectory(run.draft.adapterDir).commands.find(item => item.name === tool);
  if (!command || command.runtime !== 'http' || command.safety !== 'write') throw fail('WRITE_RUNTIME_REQUIRED', 'Standalone write verification currently supports HTTP commands.');
  return command;
}

function normalizeFixture(run, command, input) {
  keys(input, ['id', 'representativeArgs', 'expectedRequest', 'successResponse', 'successExpectation', 'failureResponse', 'failureExpectation', 'effect']);
  if (JSON.stringify(input).length > 40000 || !/^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$/.test(input.id || '')) invalid('Provide a portable fixture id and at most 40000 characters.');
  dataOnly(input);
  if (!object(input.representativeArgs) || Object.hasOwn(input.representativeArgs, '__confirmed')) invalid('Author arguments without __confirmed; the verifier controls confirmation.');
  const expected = input.expectedRequest;
  keys(expected, ['url', 'method', 'body', 'headers']);
  if (!['POST', 'PUT', 'PATCH', 'DELETE'].includes(expected.method)) invalid('Expected request must be a write method.');
  const url = new URL(expected.url);
  if ([...url.searchParams.keys()].some(key => /token|cookie|auth|password|secret|session|credential|api.?key|csrf|ticket/i.test(key))) invalid('Use the HTTP auth contract instead of credential query values.');
  if (!command.http.origins.includes(url.origin) || url.username || url.password || url.hash) invalid('Expected request must use the declared command origin.');
  const plan = run.plan.tools.find(tool => `${run.siteKey}.${tool.name.replace(/_/g, '-')}` === command.name);
  const source = run.candidates[plan.sourceApiIndexes[0]];
  if (expected.method !== source.method || structuralUrl(expected.url) !== source.url) invalid('Expected request must match the declared/observed source method and structural URL.');
  if (expected.headers !== undefined && (!object(expected.headers) || Object.keys(expected.headers).some(key => key !== 'content-type') || Object.values(expected.headers).some(value => typeof value !== 'string' || /[\r\n\0]/.test(value)))) invalid('Write fixtures only author lower-case content-type; credentials come from the HTTP contract.');
  if (expected.body != null && typeof expected.body !== 'string' && expected.headers?.['content-type'] !== undefined && expected.headers['content-type'] !== 'application/json') invalid('Structured JSON bodies use application/json.');
  for (const name of ['successResponse', 'failureResponse']) {
    keys(input[name], ['status', 'body']);
    const status = input[name].status;
    if (!Number.isInteger(status) || (name === 'successResponse' ? status < 200 || status > 299 : status < 400 || status > 599)) invalid('Mock responses require success 2xx and failure 4xx/5xx statuses.');
  }
  for (const name of ['successExpectation', 'failureExpectation']) if (!object(input[name]) || !Object.keys(input[name]).length) invalid('Mock interpretations must be non-empty objects.');
  keys(input.effect, ['readback', 'before', 'after']);
  keys(input.effect.readback, ['url']);
  assertReadRequest(input.effect.readback, run.origin, run.allowedOrigins || []);
  const readUrl = new URL(input.effect.readback.url);
  if (!command.http.origins.includes(readUrl.origin) || readUrl.username || readUrl.password || readUrl.hash) invalid('Readback must use the same HTTP origin contract.');
  const assertions = normalizeVerificationCases(['before', 'after'].map(id => ({ id, args: {}, expect: input.effect[id] })));
  const before = assertions[0].expect, after = assertions[1].expect;
  if (!Object.entries(before.equals || {}).some(([key, value]) => !key.includes('*') && Object.hasOwn(after.equals || {}, key) && !Object.is(value, after.equals[key]))) invalid('Before/after need a changed scalar equals assertion at the same exact path.');
  return clone({ ...input, effect: { readback: input.effect.readback, before, after } });
}

export function writeCase(service, run, args, editing) {
  const tool = textArg(args.tool, 'tool', 200), command = writeCommand(run, tool);
  const fixtures = writeFixtures(run), fixture = fixtures.commands[command.id] || null;
  if (!editing) return { tool, fixture, hash: hash(fixture) };
  if (args.expectedHash !== hash(fixture)) throw fail('STALE_VERIFICATION', 'Read the current write fixture hash before editing.');
  fixtures.commands[command.id] = normalizeFixture(run, command, args.fixture);
  if (JSON.stringify(fixtures).length > 500000) invalid('Write fixtures exceed the task limit.');
  const file = assertManagedFile(path.dirname(run.draft.adapterDir), `.generation/${run.siteKey}/write-verification.json`);
  fs.writeFileSync(file, JSON.stringify(fixtures), { mode: 0o600 });
  run.validation = null; run.runtimeDigest = null; run.runtimeSummary = null; run.review = null;
  service.update(run, 'draft', 'Write fixture changed. Validate mocks and read commands before reviewing the real write.');
  return { tool, hash: hash(fixtures.commands[command.id]) };
}

export function writeReview(service, run, tool) {
  const command = writeCommand(run, textArg(tool, 'tool', 200));
  const digest = writeProofDigest(run);
  if (!run.validation?.passed || run.preWriteDigest !== digest) throw fail('VALIDATION_REQUIRED', 'Validate the current draft and mocks before reviewing a write.');
  const fixture = normalizeFixture(run, command, writeFixtures(run).commands[command.id]);
  const reviewId = hash({ digest, tool: command.name, fixture });
  const previous = run.writeExecutions?.find(item => item.reviewId === reviewId);
  return { reviewId, digest, tool: command.name, fixture, http: command.http,
    consumed: Boolean(previous), execution: previous || null, requiresConfirmation: true,
    policy: 'One real write after a successful before check; no redirects, retries or rollback. Readback is an independent GET.' };
}

export function finishWriteValidation(service, run) {
  const digest = writeProofDigest(run);
  const writes = plannedWrites(run);
  if (run.preWriteDigest === digest && writes.every(tool => run.writeExecutions?.some(item => item.tool === tool && item.digest === digest && item.status === 'verified'))) {
    run.runtimeDigest = readPackageDirectory(run.draft.adapterDir).digest;
    run.verifiedAt = new Date().toISOString();
    service.update(run, 'review_ready', 'Read commands, write mocks and real write effects passed. Review before installation.');
  } else service.update(run, 'write_review_ready', 'Review each pending real write explicitly. Ordinary validate never dispatches writes.');
}

const cookieResolver = service => async payload => (await service.request({ type: 'http_credentials', payload }, 10000)).cookies;
async function readEffect(service, execution, signal, phase) {
  const client = createHttpClient({ safety: 'read', http: execution.http }, { signal, redirects: false,
    resolveCookies: cookieResolver(service), validateRequest: input => assertReadRequest(input, execution.http.origins[0], execution.http.origins) });
  try {
    const value = await client.request(execution.effect.readback);
    return (await strictVerifier())(value, execution.effect[phase]).length === 0;
  } finally { client.dispose(); }
}

export function verifyWrite(service, run, args) {
  const previous = run.writeExecutions?.find(item => item.reviewId === args.reviewId);
  // Even cancellation/restart or a lost CLI response cannot re-dispatch this review.
  if (previous) {
    if (previous.tool !== args.tool) throw fail('STALE_REVIEW', 'Review belongs to a different tool.');
    return service.summary(run);
  }
  const review = writeReview(service, run, args.tool);
  if (args.reviewId !== review.reviewId) throw fail('STALE_REVIEW', 'Review the current exact write case before dispatch.');
  if (args.confirmed !== true && args.confirmed !== 'true') throw fail('CONFIRMATION_REQUIRED', 'Explicit consent to this exact write and readback is required.');
  if ((run.writeExecutions?.length || 0) >= 100) throw fail('WRITE_LIMIT', 'This task has consumed 100 write reviews.');
  const execution = { reviewId: review.reviewId, digest: review.digest, tool: review.tool, status: 'preparing', dispatched: false,
    at: new Date().toISOString(), http: clone(review.http), effect: clone(review.fixture.effect) };
  run.writeExecutions = [...(run.writeExecutions || []), execution];
  run.runtimeDigest = null; run.review = null;
  return service.launch(run, 'verifying_write', async signal => {
    const controller = new AbortController(), abort = () => controller.abort();
    signal.addEventListener('abort', abort, { once: true });
    if (signal.aborted) controller.abort();
    const timer = setTimeout(abort, 30000);
    let violation = false, calls = 0;
    try {
      await service.checkTab(run);
      if (!await readEffect(service, execution, controller.signal, 'before')) throw fail('WRITE_PRECONDITION_FAILED', 'The before assertion failed; no write was sent.');
      if (controller.signal.aborted) throw fail('HTTP_ABORTED', 'Write verification cancelled.');
      if (writeProofDigest(run) !== review.digest) throw fail('STALE_DRAFT', 'Draft or fixture changed before write dispatch.');
      const pkg = readPackageDirectory(run.draft.adapterDir), command = pkg.commands.find(item => item.name === review.tool);
      const { result } = await runHttpTool({ adapter: { root: run.draft.adapterDir, digest: pkg.digest }, command }, { ...review.fixture.representativeArgs, __confirmed: true }, {
        signal: controller.signal, resolveCookies: cookieResolver(service),
        onRequestFailure: () => { violation = true; },
        validateRequest: input => {
          const observed = normalizeHttpWriteRequest(input);
          // Header keys and all other request options are also bound; no hidden
          // extra calls are permitted even if the authored handler catches errors.
          if (++calls !== 1 || !compareHttpWriteRequest(observed, review.fixture.expectedRequest)
            || Object.keys(input).some(key => !['url', 'method', 'headers', 'body', 'json'].includes(key))) {
            violation = true; throw fail('WRITE_REQUEST_MISMATCH', 'The write differs from its reviewed request or attempts another request.');
          }
        },
        beforeDispatch: () => {
          if (controller.signal.aborted || writeProofDigest(run) !== review.digest) { violation = true; throw fail('STALE_DRAFT', 'Write verification changed before dispatch.'); }
          execution.status = 'dispatching'; execution.dispatched = true;
          service.save(run);
        },
      });
      if (violation || calls !== 1 || !execution.dispatched || result?.ok === false || result?.error || !subsetMatches(result, review.fixture.successExpectation)) throw fail('WRITE_RESULT_MISMATCH', 'The command result or request count failed the reviewed case.');
      execution.responseVerified = true;
      execution.effectVerified = await readEffect(service, execution, controller.signal, 'after');
      if (!execution.effectVerified) throw fail('WRITE_EFFECT_MISMATCH', 'Write response succeeded but the independent after assertion failed.');
      if (controller.signal.aborted) throw fail('HTTP_ABORTED', 'Write verification cancelled after dispatch.');
      if (writeProofDigest(run) !== review.digest) throw fail('STALE_DRAFT', 'Draft changed during write verification.');
      execution.status = 'verified';
    } catch (error) {
      execution.status = execution.dispatched ? 'uncertain' : 'not_dispatched';
      execution.error = { code: error.code || 'WRITE_VERIFICATION_FAILED' };
    } finally {
      clearTimeout(timer); signal.removeEventListener('abort', abort); controller.abort();
      // Preserve cancellation, while retaining the durable possible-effect state.
      service.save(run);
    }
    if (!signal.aborted) finishWriteValidation(service, run);
  });
}

/** Re-inspection can establish the effect, never replays or blesses a failed handler. */
export async function readbackWrite(service, run, reviewId) {
  if (service.jobs.has(run.taskId)) throw fail('TASK_BUSY', 'Wait for the in-flight operation to settle before reading its effect.');
  const execution = run.writeExecutions?.find(item => item.reviewId === reviewId);
  if (!execution) throw fail('STALE_REVIEW', 'No consumed write review with that ID.');
  const controller = new AbortController(), timer = setTimeout(() => controller.abort(), 15000);
  try {
    const passed = await readEffect(service, execution, controller.signal, 'after');
    execution.readback = { at: new Date().toISOString(), passed };
    service.save(run);
    return { reviewId, passed, originalStatus: execution.status, writeReplayed: false };
  } finally { clearTimeout(timer); controller.abort(); }
}
